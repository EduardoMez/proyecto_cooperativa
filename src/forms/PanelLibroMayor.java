    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
      Connection con = null;
    try {
        con = Conexion.conectar();
        LibroMayorDAO dao = new LibroMayorDAO();
        Cuenta cuenta = (Cuenta) cmbCuenta.getSelectedItem();
        if (cuenta == null) {
            JOptionPane.showMessageDialog(this,
                    "Seleccione una cuenta");
            return;
        }
        // convertir texto dd/MM/yyyy a Date
        java.text.SimpleDateFormat sdf =
                new java.text.SimpleDateFormat("dd/MM/yyyy");

        java.util.Date inicio =
                sdf.parse(ftxtFechaInicio.getText());
        java.util.Date fin =
                sdf.parse(ftxtFechaFin.getText());
        java.sql.Date fechaInicio =
                new java.sql.Date(inicio.getTime());
        java.sql.Date fechaFin =
                new java.sql.Date(fin.getTime());
        List<LibroMayor> lista =dao.listarLibroMayor(cuenta.getId(),fechaInicio,fechaFin,con);

        llenarTabla(lista);

    } catch (Exception e) {

        JOptionPane.showMessageDialog(this,
                "Error: " + e.getMessage());
    }
    }//GEN-LAST:event_jButton1ActionPerformed

